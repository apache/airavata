package org.apache.airavata.models.sharing.registry;

/**
 * Domain is the entity that enables multi-tenancy in this component. Every tenant will be
 * operating separately in its own silo which is identified by the domain id.
 *
 * <p>Plain-POJO replacement for the generated
 * {@code org.apache.airavata.sharing.registry.models.proto.Domain}.
 *
 * @param domainId Will be generated by the server based on the domain name.
 * @param name A single word name that identifies the domain e.g seagrid, ultrascan.
 * @param description A short description for the domain.
 * @param createdTime Will be set by the system.
 * @param updatedTime Will be set by the system.
 * @param initialUserGroupId New users will automatically be added to this group.
 */
public record Domain(
        String domainId, String name, String description, long createdTime, long updatedTime,
        String initialUserGroupId) {

    public static Builder newBuilder() {
        return new Builder();
    }

    public Builder toBuilder() {
        return new Builder(this);
    }

    public static final class Builder {
        private String domainId = "";
        private String name = "";
        private String description = "";
        private long createdTime;
        private long updatedTime;
        private String initialUserGroupId = "";

        private Builder() {}

        private Builder(Domain source) {
            this.domainId = source.domainId;
            this.name = source.name;
            this.description = source.description;
            this.createdTime = source.createdTime;
            this.updatedTime = source.updatedTime;
            this.initialUserGroupId = source.initialUserGroupId;
        }

        public Builder setDomainId(String domainId) {
            this.domainId = domainId;
            return this;
        }

        public Builder setName(String name) {
            this.name = name;
            return this;
        }

        public Builder setDescription(String description) {
            this.description = description;
            return this;
        }

        public Builder setCreatedTime(long createdTime) {
            this.createdTime = createdTime;
            return this;
        }

        public Builder setUpdatedTime(long updatedTime) {
            this.updatedTime = updatedTime;
            return this;
        }

        public Builder setInitialUserGroupId(String initialUserGroupId) {
            this.initialUserGroupId = initialUserGroupId;
            return this;
        }

        public Domain build() {
            return new Domain(domainId, name, description, createdTime, updatedTime, initialUserGroupId);
        }
    }
}
